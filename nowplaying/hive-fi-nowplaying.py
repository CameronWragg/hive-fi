# Scrolling cadence. Each frame is a full 240x240 SPI transfer, which is the
# expensive part on a Pi Zero 2 W, so this is deliberately modest.
SCROLL_INTERVAL = 1.0 / 10


def frame_interval(state: PlayerState, scrolling: bool) -> float:
    """How long we can sleep before the frame needs redrawing."""
    if state.showing_volume():
        return 0.1
    if state.idle():
        return 1.0
    if scrolling:
        return SCROLL_INTERVAL
    # Nothing is moving except the progress bar and the elapsed clock.
    return 0.5 if state.playing else 1.0


def is_animating(state: PlayerState, scrolling: bool) -> bool:
    if state.idle():
        return False
    return scrolling or state.playing or state.showing_volume()


def run(args: argparse.Namespace) -> int:
    renderer = Renderer(Path(args.logo))
    output = (
        PreviewOutput(Path(args.preview))
        if args.preview
        else LcdOutput(rotation=args.rotation, spi_speed_hz=args.spi_speed)
    )
    pipe = MetadataPipe(args.pipe)
    state = PlayerState()

    running = True

    def stop(signum, _frame):
        nonlocal running
        LOG.info("caught signal %s, shutting down", signal.Signals(signum).name)
        running = False

    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)

    last_revision = -1
    last_drawn = 0.0
    draw_failing = False

    try:
        while running:
            scrolling = not state.idle() and renderer.needs_scroll(state)
            interval = frame_interval(state, scrolling)

            for item in pipe.read(interval):
                LOG.debug("%s/%s (%d bytes)", item.type, item.code, len(item.payload))
                try:
                    apply_item(state, item)
                except Exception:  # a malformed item must not kill the display
                    LOG.exception(
                        "failed to apply metadata item %s/%s", item.type, item.code
                    )

            now = time.monotonic()
            due = state.revision != last_revision or (
                is_animating(state, scrolling) and now - last_drawn >= interval * 0.9
            )
            if due:
                try:
                    output.show(renderer.render(state, now))
                    draw_failing = False
                except Exception:
                    # Frames can come ten a second, so only report the first
                    # failure of a run rather than filling the journal.
                    if not draw_failing:
                        LOG.exception("failed to draw frame")
                        draw_failing = True
                last_revision = state.revision
                last_drawn = now
    finally:
        pipe.close()
        if not args.preview and args.clear_on_exit:
            try:
                output.show(renderer.render(PlayerState(), time.monotonic()))
            except Exception:
                LOG.debug("could not restore the idle screen", exc_info=True)

    return 0


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--pipe",
        default=os.environ.get("HIVE_FI_METADATA_PIPE", DEFAULT_PIPE),
        help="shairport-sync metadata pipe (default: %(default)s)",
    )
    parser.add_argument(
        "--logo",
        default=os.environ.get("HIVE_FI_LOGO", str(DEFAULT_LOGO)),
        help="image shown when nothing is playing (default: %(default)s)",
    )
    parser.add_argument(
        "--rotation",
        type=int,
        choices=(0, 90, 180, 270),
        default=int(os.environ.get("HIVE_FI_ROTATION", 90)),
        help="display rotation in degrees (default: %(default)s)",
    )
    parser.add_argument(
        "--spi-speed",
        type=int,
        default=SPI_SPEED_HZ,
        help="SPI clock in Hz (default: %(default)s)",
    )
    parser.add_argument(
        "--preview",
        metavar="PATH",
        help="write frames to this PNG instead of the LCD, for development",
    )
    parser.add_argument(
        "--clear-on-exit",
        action="store_true",
        help="show the idle logo when the service stops",
    )
    parser.add_argument(
        "--log-level",
        default=os.environ.get("HIVE_FI_LOG_LEVEL", "INFO"),
        help="logging level (default: %(default)s)",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    logging.basicConfig(
        level=getattr(logging, args.log_level.upper(), logging.INFO),
        format="%(levelname)s %(message)s",
    )
    try:
        return run(args)
    except KeyboardInterrupt:
        return 0
    except Exception:
        LOG.exception("hive-fi-nowplaying failed")
        return 1


if __name__ == "__main__":
    sys.exit(main())
