class LcdOutput:
    """The Pirate Audio ST7789 panel.

    The backlight (BCM 13) is deliberately left alone: hive-fi-buttons owns it
    so that it can dim the panel with PWM.  Claiming it here too would make the
    two services fight over the same GPIO line.
    """

    def __init__(self, rotation: int = 90, spi_speed_hz: int = SPI_SPEED_HZ) -> None:
        from st7789 import BG_SPI_CS_FRONT, ST7789

        self._display = ST7789(
            port=SPI_PORT,
            cs=BG_SPI_CS_FRONT,
            dc=DC_PIN,
            width=SIZE,
            height=SIZE,
            rotation=rotation,
            spi_speed_hz=spi_speed_hz,
        )

    def show(self, image: Image.Image) -> None:
        self._display.display(image)


class PreviewOutput:
    """Writes frames to a PNG instead of the LCD, for working off-device."""

    def __init__(self, path: Path) -> None:
        self.path = path

    def show(self, image: Image.Image) -> None:
        image.save(self.path)


