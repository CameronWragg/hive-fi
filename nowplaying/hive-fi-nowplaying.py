def load_font(candidates: tuple[str, ...], size: int) -> ImageFont.ImageFont:
    for path in candidates:
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            continue
    LOG.warning("no TrueType font found, falling back to the bitmap default")
    return ImageFont.load_default()


def text_width(draw: ImageDraw.ImageDraw, text: str, font) -> int:
    if not text:
        return 0
    left, _, right, _ = draw.textbbox((0, 0), text, font=font)
    return int(right - left)


def marquee_offset(
    overflow: int, now: float, speed: float = 26.0, dwell: float = 1.6
) -> int:
    """Ease a too-wide line back and forth, pausing at each end."""
    if overflow <= 0:
        return 0
    travel = overflow / speed
    phase = now % (2 * (travel + dwell))
    if phase < dwell:
        return 0
    phase -= dwell
    if phase < travel:
        return int(overflow * (phase / travel))
    phase -= travel
    if phase < dwell:
        return overflow
    return int(overflow * (1.0 - (phase - dwell) / travel))


def format_time(seconds: float) -> str:
    seconds = int(max(0.0, seconds))
    hours, remainder = divmod(seconds, 3600)
    minutes, secs = divmod(remainder, 60)
    if hours:
        return f"{hours}:{minutes:02d}:{secs:02d}"
    return f"{minutes}:{secs:02d}"


@dataclass
class Line:
    text: str
    font: ImageFont.ImageFont
    colour: tuple[int, int, int]
    height: int
    gap: int


class Renderer:
    """Composes the 240x240 frame from the current player state."""

    BOTTOM_MARGIN = 8
    SIDE_MARGIN = 10
    PROGRESS_HEIGHT = 12
    PROGRESS_BAR_HEIGHT = 4
    SCRIM_LEAD = 34

    def __init__(self, logo_path: Path, size: int = SIZE) -> None:
        self.size = size
        self.title_font = load_font(BOLD_FONTS, 21)
        self.artist_font = load_font(REGULAR_FONTS, 15)
        self.album_font = load_font(REGULAR_FONTS, 13)
        self.time_font = load_font(REGULAR_FONTS, 11)
        self._measure = ImageDraw.Draw(Image.new("RGB", (1, 1)))
        self._scrims: dict[int, Image.Image] = {}
        self._artwork_cache: tuple[bytes, Image.Image] | None = None
        self._logo = self._load_logo(logo_path)

    # -- backgrounds -------------------------------------------------------

    def _load_logo(self, path: Path) -> Image.Image:
        try:
            with Image.open(path) as image:
                return self._cover(image)
        except (OSError, ValueError) as exc:
            LOG.warning("could not load logo %s: %s", path, exc)
            fallback = Image.new("RGB", (self.size, self.size), (16, 14, 10))
            draw = ImageDraw.Draw(fallback)
            label = "hive-fi"
            width = text_width(draw, label, self.title_font)
            draw.text(
                ((self.size - width) // 2, self.size // 2 - 12),
                label,
                font=self.title_font,
                fill=(235, 190, 60),
            )
            return fallback

    def _cover(self, image: Image.Image) -> Image.Image:
        """Scale and centre-crop an image to fill the square display."""
        image = ImageOps.exif_transpose(image).convert("RGB")
        return ImageOps.fit(image, (self.size, self.size), method=Image.LANCZOS)

    def _artwork(self, data: bytes | None) -> Image.Image | None:
        if not data:
            return None
        if self._artwork_cache and self._artwork_cache[0] == data:
            return self._artwork_cache[1]
        try:
            with Image.open(io.BytesIO(data)) as image:
                rendered = self._cover(image)
        except (OSError, ValueError) as exc:
            LOG.warning("could not decode cover art (%d bytes): %s", len(data), exc)
            return None
        self._artwork_cache = (data, rendered)
        return rendered

    def _scrim(self, top: int) -> Image.Image:
        """A cached bottom-up gradient mask that keeps text legible over art."""
        cached = self._scrims.get(top)
        if cached is not None:
            return cached
        column = Image.new("L", (1, self.size), 0)
        pixels = column.load()
        span = max(1, self.size - 1 - top)
        for y in range(top, self.size):
            pixels[0, y] = int(235 * ((y - top) / span) ** 0.6)
        mask = column.resize((self.size, self.size))
        self._scrims[top] = mask
        return mask

    # -- frame -------------------------------------------------------------

    def needs_scroll(self, state: PlayerState) -> bool:
        """True when a line is too wide to fit and has to be scrolled."""
        available = self.size - 2 * self.SIDE_MARGIN
        return any(
            text_width(self._measure, line.text, line.font) > available
            for line in self._lines(state)
        )

    def render(self, state: PlayerState, now: float) -> Image.Image:
        if state.idle():
            return self._logo.copy()

        artwork = self._artwork(state.track.artwork)
        frame = artwork.copy() if artwork is not None else self._placeholder()
        draw = ImageDraw.Draw(frame)

        lines = self._lines(state)
        duration = state.duration()
        show_progress = duration > 0

        # Lay the text out from the bottom of the screen upwards so the frame
        # still looks right when the source gives us no album or no duration.
        cursor = self.size - self.BOTTOM_MARGIN
        progress_top = None
        if show_progress:
            cursor -= self.PROGRESS_HEIGHT
            progress_top = cursor
            cursor -= 10

        placed: list[tuple[Line, int]] = []
        for line in reversed(lines):
            cursor -= line.height
            placed.append((line, cursor))
            cursor -= line.gap

        scrim_top = max(0, cursor - self.SCRIM_LEAD)
        frame.paste((0, 0, 0), (0, 0, self.size, self.size), self._scrim(scrim_top))

        for line, top in placed:
            self._draw_line(frame, draw, line, top, now)

        if show_progress and progress_top is not None:
            self._draw_progress(draw, state.elapsed(), duration, progress_top)

        if not state.playing:
            frame = self._draw_paused_badge(frame)
        if state.showing_volume() and state.volume is not None:
            self._draw_volume(ImageDraw.Draw(frame), state.volume)

        return frame

    def _placeholder(self) -> Image.Image:
        """A dimmed logo, used while a track has details but no cover art."""
        return Image.blend(
            self._logo, Image.new("RGB", (self.size, self.size), (0, 0, 0)), 0.55
        )

    def _lines(self, state: PlayerState) -> list[Line]:
        track = state.track
        candidates = (
            (track.title or "Unknown track", self.title_font, (255, 255, 255), 27, 3),
            (track.artist, self.artist_font, (226, 226, 226), 20, 2),
            (track.album, self.album_font, (168, 168, 168), 17, 0),
        )
        return [
            Line(text, font, colour, height, gap)
            for text, font, colour, height, gap in candidates
            if text
        ]

    def _draw_line(
        self,
        frame: Image.Image,
        draw: ImageDraw.ImageDraw,
        line: Line,
        top: int,
        now: float,
    ) -> None:
        available = self.size - 2 * self.SIDE_MARGIN
        width = text_width(draw, line.text, line.font)
        if width <= available:
            draw.text(
                (self.SIDE_MARGIN, top), line.text, font=line.font, fill=line.colour
            )
            return

        # Too wide to fit: render the whole line once onto a transparent strip
        # and slide a window over it, fading the ends so it does not clip hard.
        strip = Image.new("RGBA", (width + 8, line.height), (0, 0, 0, 0))
        ImageDraw.Draw(strip).text(
            (0, 0), line.text, font=line.font, fill=line.colour + (255,)
        )
        offset = marquee_offset(width - available, now)
        window = strip.crop((offset, 0, offset + available, line.height))
        window.putalpha(
            ImageChops.multiply(
                window.getchannel("A"), _fade_mask(available, line.height)
            )
        )
        frame.paste(window, (self.SIDE_MARGIN, top), window)

    def _draw_progress(
        self, draw: ImageDraw.ImageDraw, elapsed: float, duration: float, top: int
    ) -> None:
        elapsed_label = format_time(elapsed)
        duration_label = format_time(duration)
        elapsed_width = text_width(draw, elapsed_label, self.time_font)
        duration_width = text_width(draw, duration_label, self.time_font)

        text_top = top + (self.PROGRESS_HEIGHT - 12) // 2
        draw.text(
            (self.SIDE_MARGIN, text_top),
            elapsed_label,
            font=self.time_font,
            fill=(200, 200, 200),
        )
        draw.text(
            (self.size - self.SIDE_MARGIN - duration_width, text_top),
            duration_label,
            font=self.time_font,
            fill=(200, 200, 200),
        )

        bar_left = self.SIDE_MARGIN + elapsed_width + 8
        bar_right = self.size - self.SIDE_MARGIN - duration_width - 8
        if bar_right <= bar_left:
            return
        bar_top = top + (self.PROGRESS_HEIGHT - self.PROGRESS_BAR_HEIGHT) // 2
        bar_bottom = bar_top + self.PROGRESS_BAR_HEIGHT
        radius = self.PROGRESS_BAR_HEIGHT // 2

        draw.rounded_rectangle(
            (bar_left, bar_top, bar_right, bar_bottom), radius=radius, fill=(96, 96, 96)
        )
        fraction = min(1.0, max(0.0, elapsed / duration)) if duration else 0.0
        played_right = bar_left + int((bar_right - bar_left) * fraction)
        if played_right > bar_left:
            draw.rounded_rectangle(
                (bar_left, bar_top, played_right, bar_bottom),
                radius=radius,
                fill=(255, 255, 255),
            )

    def _draw_paused_badge(self, frame: Image.Image) -> Image.Image:
        overlay = Image.new("RGBA", (self.size, self.size), (0, 0, 0, 0))
        draw = ImageDraw.Draw(overlay)
        centre_x, centre_y, radius = self.size - 28, 28, 17
        draw.ellipse(
            (
                centre_x - radius,
                centre_y - radius,
                centre_x + radius,
                centre_y + radius,
            ),
            fill=(0, 0, 0, 130),
        )
        for offset in (-5, 2):
            draw.rectangle(
                (centre_x + offset, centre_y - 8, centre_x + offset + 3, centre_y + 8),
                fill=(255, 255, 255, 235),
            )
        return Image.alpha_composite(frame.convert("RGBA"), overlay).convert("RGB")

    def _draw_volume(self, draw: ImageDraw.ImageDraw, level: float) -> None:
        left, right = self.size - 12, self.size - 6
        top, bottom = 46, self.size - 92
        draw.rounded_rectangle((left, top, right, bottom), radius=3, fill=(60, 60, 60))
        filled_top = bottom - int((bottom - top) * level)
        if filled_top < bottom:
            draw.rounded_rectangle(
                (left, filled_top, right, bottom), radius=3, fill=(255, 255, 255)
            )


@lru_cache(maxsize=8)
def _fade_mask(width: int, height: int, fade: int = 14) -> Image.Image:
    """Soften the ends of a scrolling line so it slides out of view."""
    mask = Image.new("L", (width, height), 255)
    pixels = mask.load()
    for x in range(min(fade, width)):
        value = int(255 * x / fade)
        for y in range(height):
            pixels[x, y] = value
            pixels[width - 1 - x, y] = value
    return mask


