ITEM_RE = re.compile(
    rb"<item>"
    rb"<type>([0-9a-fA-F]{1,8})</type>"
    rb"<code>([0-9a-fA-F]{1,8})</code>"
    rb"<length>(\d+)</length>"
    rb'(?:\n<data encoding="base64">\n(.*?)</data>)?'
    rb"</item>\n?",
    re.DOTALL,
)


def fourcc(digits: bytes) -> str:
    """Turn the hex form of a four-character code back into text."""
    try:
        raw = bytes.fromhex(digits.decode("ascii").rjust(8, "0"))
    except (ValueError, UnicodeDecodeError):
        return ""
    return raw.decode("ascii", "replace")


@dataclass(frozen=True)
class Item:
    type: str
    code: str
    payload: bytes

    def text(self) -> str:
        return self.payload.decode("utf-8", "replace").strip("\x00")


class MetadataPipe:
    """Incremental reader for the shairport-sync metadata FIFO.

    The FIFO is opened non-blocking, and a write end is held open alongside it
    so the read end never reports EOF when shairport-sync is idle or restarts.
    """

    def __init__(self, path: str) -> None:
        self.path = path
        self._read_fd: int | None = None
        self._write_fd: int | None = None
        self._inode: int | None = None
        self._buffer = b""
        self._warned_missing = False

    def close(self) -> None:
        for attr in ("_read_fd", "_write_fd"):
            fd = getattr(self, attr)
            if fd is not None:
                with contextlib.suppress(OSError):
                    os.close(fd)
                setattr(self, attr, None)
        self._buffer = b""
        self._inode = None

    def _open(self) -> bool:
        try:
            stat = os.stat(self.path)
        except FileNotFoundError:
            if not self._warned_missing:
                LOG.warning("waiting for metadata pipe %s to appear", self.path)
                self._warned_missing = True
            return False
        self._warned_missing = False

        try:
            read_fd = os.open(self.path, os.O_RDONLY | os.O_NONBLOCK)
            # Holding a writer open keeps the reader from seeing EOF between
            # shairport-sync play sessions.
            write_fd = os.open(self.path, os.O_WRONLY | os.O_NONBLOCK)
        except OSError as exc:
            LOG.warning("cannot open metadata pipe %s: %s", self.path, exc)
            return False

        self.close()
        self._read_fd, self._write_fd, self._inode = read_fd, write_fd, stat.st_ino
        LOG.info("reading metadata from %s", self.path)
        return True

    def _reopen_if_replaced(self) -> None:
        """Follow the pipe if shairport-sync recreates it under the same name."""
        try:
            if os.stat(self.path).st_ino != self._inode:
                LOG.info("metadata pipe %s was replaced, reopening", self.path)
                self._open()
        except FileNotFoundError:
            self.close()

    def read(self, timeout: float) -> list[Item]:
        """Wait up to `timeout` seconds and return any complete items read."""
        if self._read_fd is None:
            if not self._open():
                time.sleep(min(timeout, 1.0))
                return []
        else:
            self._reopen_if_replaced()
            if self._read_fd is None:
                time.sleep(min(timeout, 1.0))
                return []

        try:
            ready, _, _ = select.select([self._read_fd], [], [], timeout)
        except InterruptedError:
            return []
        if not ready:
            return []

        try:
            chunk = os.read(self._read_fd, 1 << 16)
        except BlockingIOError:
            return []
        except OSError as exc:
            LOG.warning("metadata pipe read failed: %s", exc)
            self.close()
            return []

        if not chunk:
            return []

        self._buffer += chunk
        return self._drain()

    def _drain(self) -> list[Item]:
        items: list[Item] = []
        end = 0
        for match in ITEM_RE.finditer(self._buffer):
            end = match.end()
            item = self._build(match)
            if item is not None:
                items.append(item)
        # Items are newline separated; drop any separator we stopped on.
        self._buffer = self._buffer[end:].lstrip(b"\n")

        if len(self._buffer) > MAX_BUFFER_BYTES:
            LOG.warning("discarding %d bytes of unparsable metadata", len(self._buffer))
            self._buffer = b""
        return items

    @staticmethod
    def _build(match: re.Match[bytes]) -> Item | None:
        type_hex, code_hex, _length, data = match.groups()
        payload = b""
        if data:
            try:
                payload = base64.b64decode(data, validate=False)
            except binascii.Error:
                LOG.debug("skipping item with undecodable payload")
                return None
        item_type, item_code = fourcc(type_hex), fourcc(code_hex)
        if not item_type or not item_code:
            return None
        return Item(item_type, item_code, payload)


