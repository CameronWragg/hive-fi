#!/usr/bin/env python3
"""Now-playing display for hive-fi.

Reads the metadata pipe published by shairport-sync, tracks what is currently
playing and renders album art, track details, playback progress and volume
changes onto the Pirate Audio ST7789 LCD.

The metadata pipe carries a stream of items shaped like::

    <item><type>73736e63</type><code>70626567</code><length>0</length></item>
    <item><type>636f7265</type><code>6d696e6d</code><length>11</length>
    <data encoding="base64">
    U29tZSBUcmFjaw==</data></item>

``type`` and ``code`` are four-character codes written as hexadecimal.  The
type is ``core`` for metadata that came from the AirPlay source (DMAP codes
such as ``minm``/``asar``/``asal``) or ``ssnc`` for messages generated by
shairport-sync itself (``PICT`` cover art, ``pbeg``/``pend`` session
delimiters, ``prgr`` progress, and so on).

See docs/shairport-sync.md for the pipe setup and the full code list.
"""

