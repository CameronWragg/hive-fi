@dataclass
class Track:
    title: str = ""
    artist: str = ""
    album: str = ""
    duration: float = 0.0
    artwork: bytes | None = None

    def described(self) -> bool:
        return bool(self.title or self.artist or self.album)


@dataclass
class PlayerState:
    """What is playing right now, assembled from the metadata stream."""

    active: bool = False
    playing: bool = False
    track: Track = field(default_factory=Track)
    volume: float | None = None
    volume_changed_at: float = 0.0

    _pending: Track = field(default_factory=Track)
    _in_bundle: bool = False
    _progress_elapsed: float = 0.0
    _progress_total: float = 0.0
    _progress_at: float = 0.0

    # Bumped whenever something worth redrawing changes.
    revision: int = 0

    def _touch(self) -> None:
        self.revision += 1

    # -- metadata bundles --------------------------------------------------

    def begin_bundle(self) -> None:
        self._pending = Track(artwork=self.track.artwork)
        self._in_bundle = True

    def end_bundle(self) -> None:
        if self._pending.described():
            if (self._pending.title, self._pending.artist, self._pending.album) != (
                self.track.title,
                self.track.artist,
                self.track.album,
            ):
                # A genuinely new track invalidates the old art until PICT lands.
                self._pending.artwork = None
                self._progress_total = 0.0
            self.track = self._pending
            self._touch()
        self._pending = Track(artwork=self.track.artwork)
        self._in_bundle = False

    def set_text(self, field_name: str, value: str) -> None:
        setattr(self._pending, field_name, value)
        if not self._in_bundle:
            # Not every source brackets its metadata with mdst/mden, so apply
            # unbracketed items immediately rather than waiting for a commit.
            setattr(self.track, field_name, value)
            self._touch()

    def set_duration(self, milliseconds: int) -> None:
        self._pending.duration = milliseconds / 1000.0
        if not self._in_bundle:
            self.track.duration = milliseconds / 1000.0

    def set_artwork(self, data: bytes) -> None:
        artwork = data or None
        if artwork != self.track.artwork:
            self.track.artwork = artwork
            self._pending.artwork = artwork
            self._touch()

    # -- transport ---------------------------------------------------------

    def session_begin(self) -> None:
        self.active = True
        self.playing = True
        self._touch()

    def session_end(self) -> None:
        self.active = False
        self.playing = False
        self.track = Track()
        self._pending = Track()
        self._in_bundle = False
        self.volume = None
        self._progress_total = 0.0
        self._progress_elapsed = 0.0
        self._touch()

    def set_playing(self, playing: bool) -> None:
        if playing != self.playing:
            # Freeze the interpolated position before changing direction.
            self._progress_elapsed = self.elapsed()
            self._progress_at = time.monotonic()
            self.playing = playing
            self.active = self.active or playing
            self._touch()

    def set_progress(self, start: int, current: int, end: int) -> None:
        elapsed = ((current - start) % RTP_MODULUS) / RTP_RATE
        total = ((end - start) % RTP_MODULUS) / RTP_RATE
        self._progress_elapsed = max(0.0, elapsed)
        self._progress_total = max(0.0, total)
        self._progress_at = time.monotonic()
        self.active = True
        self._touch()

    def set_volume(self, airplay_volume: float) -> None:
        if airplay_volume <= AIRPLAY_VOLUME_MUTE:
            level = 0.0
        else:
            level = (airplay_volume - AIRPLAY_VOLUME_MIN) / -AIRPLAY_VOLUME_MIN
        level = min(1.0, max(0.0, level))
        if self.volume is None or abs(level - self.volume) > 1e-6:
            self.volume = level
            self.volume_changed_at = time.monotonic()
            self._touch()

    # -- derived -----------------------------------------------------------

    def duration(self) -> float:
        return self._progress_total or self.track.duration

    def elapsed(self) -> float:
        elapsed = self._progress_elapsed
        if self.playing and self._progress_at:
            elapsed += time.monotonic() - self._progress_at
        total = self.duration()
        return min(elapsed, total) if total else max(0.0, elapsed)

    def showing_volume(self) -> bool:
        return (
            self.volume is not None
            and time.monotonic() - self.volume_changed_at < VOLUME_OVERLAY_SECONDS
        )

    def idle(self) -> bool:
        return not self.active and not self.track.described()


def apply_item(state: PlayerState, item: Item) -> None:
    """Fold a single metadata item into the player state."""
    if item.type == "core":
        field_name = CORE_TEXT_CODES.get(item.code)
        if field_name:
            state.set_text(field_name, item.text())
        elif item.code == "astm" and len(item.payload) >= 4:
            state.set_duration(struct.unpack(">I", item.payload[:4])[0])
        return

    if item.type != "ssnc":
        return

    if item.code == "mdst":
        state.begin_bundle()
    elif item.code == "mden":
        state.end_bundle()
    elif item.code == "PICT":
        state.set_artwork(item.payload)
    elif item.code == "pbeg":
        state.session_begin()
    elif item.code == "pend":
        state.session_end()
    elif item.code in ("pfls", "paus"):
        state.set_playing(False)
    elif item.code in ("prsm", "pres"):
        state.set_playing(True)
    elif item.code == "prgr":
        parts = item.text().split("/")
        if len(parts) == 3:
            try:
                state.set_progress(*(int(part) for part in parts))
            except ValueError:
                LOG.debug("unparsable progress string %r", item.text())
    elif item.code == "pvol":
        parts = item.text().split(",")
        if parts:
            try:
                state.set_volume(float(parts[0]))
            except ValueError:
                LOG.debug("unparsable volume string %r", item.text())


